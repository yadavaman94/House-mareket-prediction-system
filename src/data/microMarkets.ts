// Helper to expand the dataset with synthetic realistic historical variations across 2021-2026
export function getExpandedHistoricalDataset(): HistoricalSale[] {
  const dataset: HistoricalSale[] = [...HISTORICAL_SALES_DATASET];
  const templates = [...HISTORICAL_SALES_DATASET];

  const streets = ['Oak Ridge', 'Cedar Valley', 'Maple Crest', 'Pine Vista', 'Lakeside Way', 'Meadowbrook', 'Highland Park', 'Summit Crest', 'Willow Creek', 'Fairview'];
  const years = [2023, 2024, 2025, 2026];
  const months = ['01', '03', '05', '07', '09', '11'];

  let counter = 500;
  for (const t of templates) {
    for (let i = 0; i < 4; i++) {
      counter++;
      const year = years[i % years.length];
      const month = months[(counter + i) % months.length];
      const day = (10 + (counter % 18)).toString().padStart(2, '0');
      const saleDate = `${year}-${month}-${day}`;

      // Time discount for older sales
      const yearsAgo = 2026 - year;
      const discountFactor = Math.max(0.82, 1 - (yearsAgo * 0.052));
      const sqftDelta = ((counter % 9) - 4) * 60;
      const finalSqft = Math.max(900, t.squareFeet + sqftDelta);

      const baseAdjustedPrice = Math.round(t.salePrice * (finalSqft / t.squareFeet) * discountFactor);
      const noise = ((counter % 13) - 6) * 8000;
      const finalSalePrice = Math.round((baseAdjustedPrice + noise) / 1000) * 1000;
      const daysOnMarket = Math.max(4, Math.min(65, Math.round(t.daysOnMarket + (yearsAgo * 3) + ((counter % 7) - 3))));
      const listRatio = 0.98 + ((counter % 6) * 0.01);
      const originalListPrice = Math.round((finalSalePrice / listRatio) / 1000) * 1000;

      dataset.push({
        ...t,
        id: `sale-synth-${counter}`,
        address: `${100 + (counter * 7)} ${streets[counter % streets.length]} Dr`,
        squareFeet: finalSqft,
        salePrice: finalSalePrice,
        originalListPrice,
        saleDate,
        daysOnMarket,
        pricePerSqFt: Math.round(finalSalePrice / finalSqft),
        schoolRating: Number(Math.min(10, Math.max(6, t.schoolRating + (((counter % 5) - 2) * 0.2))).toFixed(1)),
        walkScore: Math.min(99, Math.max(30, t.walkScore + ((counter % 9) - 4))),
        distanceToTechHub: Number(Math.max(0.4, t.distanceToTechHub + (((counter % 7) - 3) * 0.4)).toFixed(1)),
      });
    }
  }

  return dataset;
}
