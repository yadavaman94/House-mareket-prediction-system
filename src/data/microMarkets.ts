// Generate structured 96-month historical time series for each market (2018-01 through 2026-08)
export function generateMarketTrendHistory(marketId: string): MonthlyTrendData[] {
  const basePrices: Record<string, { startPrice: number; startPpsf: number; rateAvg: number }> = {
    'kirkland-bellevue': { startPrice: 910000, startPpsf: 495, rateAvg: 4.5 },
    'austin-central': { startPrice: 520000, startPpsf: 320, rateAvg: 4.5 },
    'denver-cherry-creek': { startPrice: 680000, startPpsf: 410, rateAvg: 4.5 },
    'silicon-valley-peninsula': { startPrice: 1650000, startPpsf: 890, rateAvg: 4.5 },
  };

  const config = basePrices[marketId] || basePrices['kirkland-bellevue'];
  const months: MonthlyTrendData[] = [];

  const startYear = 2018;
  const startMonth = 1;
  const totalMonths = 104; // Jan 2018 to Aug 2026

  let currentPrice = config.startPrice;
  let currentPpsf = config.startPpsf;

  const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

  for (let i = 0; i < totalMonths; i++) {
    const year = startYear + Math.floor((startMonth - 1 + i) / 12);
    const m = ((startMonth - 1 + i) % 12) + 1;
    const monthStr = `${year}-${m.toString().padStart(2, '0')}`;
    const label = `${monthNames[m - 1]} ${year}`;

    // Macro market phases:
    // 2018 - 2019: Steady modest growth +0.4%/mo
    // 2020 Q2 - 2021 Q4: Massive pandemic / low rate expansion +1.2%/mo
    // 2022 - 2023 Q2: Fed rate shock correction -0.5%/mo
    // 2023 Q3 - 2026: Supply lock-in recovery & AI economic drivers +0.55%/mo
    let monthlyGrowth = 0.0035;
    let mortgageRate = 4.4;

    if (year === 2018 || year === 2019) {
      monthlyGrowth = 0.003 + (Math.sin(m) * 0.002);
      mortgageRate = 4.2 + (year === 2018 ? 0.3 : -0.2);
    } else if (year === 2020) {
      if (m < 4) monthlyGrowth = 0.002;
      else monthlyGrowth = 0.011 + (m * 0.0005);
      mortgageRate = 3.1 - (m * 0.04);
    } else if (year === 2021) {
      monthlyGrowth = 0.013 + (Math.sin(m) * 0.003);
      mortgageRate = 2.96 + (m * 0.015);
    } else if (year === 2022) {
      if (m < 5) {
        monthlyGrowth = 0.008;
        mortgageRate = 3.8 + (m * 0.4);
      } else {
        monthlyGrowth = -0.009; // rate hike shock
        mortgageRate = 5.5 + (m * 0.15);
      }
    } else if (year === 2023) {
      if (m < 8) {
        monthlyGrowth = -0.002;
        mortgageRate = 6.8 + (Math.sin(m) * 0.3);
      } else {
        monthlyGrowth = 0.004;
        mortgageRate = 7.2;
      }
    } else if (year === 2024) {
      monthlyGrowth = 0.0045 + (m >= 3 && m <= 7 ? 0.003 : 0);
      mortgageRate = 6.75 - (m * 0.03);
    } else if (year === 2025) {
      monthlyGrowth = 0.0048 + (m >= 3 && m <= 7 ? 0.003 : 0);
      mortgageRate = 6.3 - (m * 0.02);
    } else {
      // 2026
      monthlyGrowth = 0.005 + (m >= 3 && m <= 6 ? 0.0025 : 0);
      mortgageRate = 5.95;
    }

    currentPrice = Math.round(currentPrice * (1 + monthlyGrowth));
    currentPpsf = Math.round(currentPpsf * (1 + monthlyGrowth));

    // Days on market & ratio calculations
    const isSpringRush = m >= 3 && m <= 6;
    const medianDaysOnMarket = Math.max(7, Math.round(18 - (monthlyGrowth * 400) + (isSpringRush ? -4 : 4)));
    const saleToListRatio = Number((1.0 + (monthlyGrowth * 2.8) + (isSpringRush ? 0.015 : -0.005)).toFixed(3));
    const activeListings = Math.max(45, Math.round(180 + (Math.sin(m * 0.5) * 60) - (monthlyGrowth * 1800)));
    const closedSales = Math.max(30, Math.round(85 + (isSpringRush ? 35 : -15)));
    const inventoryMonths = Number((activeListings / (closedSales || 1)).toFixed(1));

    months.push({
      month: monthStr,
      label,
      medianSalePrice: currentPrice,
      medianPricePerSqFt: currentPpsf,
      activeListings,
      closedSales,
      medianDaysOnMarket,
      saleToListRatio,
      inventoryMonths,
      mortgageRateAvg: Number(mortgageRate.toFixed(2)),
    });
  }

  return months;
}

